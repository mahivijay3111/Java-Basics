public class mathconcepts {
  public static void main(String[] args) {
    System.out.println(Math.PI);
    System.out.println(Math.E);

    double result;
    result = Math.pow(2,3);
    System.out.println(result);

    double result2;
    result2 = Math.abs(-5);
    System.out.println(result2);

    double result3;
    result3 = Math.sqrt(9);
    System.out.println(result3);

    double result4;
    result4 = Math.round(3.14);   //OR Math.ceil() ROUND UP and for ROUND DOWN we use Math.floor()
    System.out.println(result4);

    double result5;
    result5 = Math.max(10,20);
    System.out.println(result5);   //Same for MIN
  }
}
